    f = p.get("format", "")
    if p["category"] == "Bundles" or f.startswith("Bundle"): return "Bundles"
    if f.startswith("Spreadsheet"): return "Spreadsheets"
    if "PDF" in f: return "Printables/PDFs"
    if f.startswith("Templates"): return "Templates"
    return "Other"

