def crumbs(r, trail):
    lis = []
    for i, (label, href) in enumerate(trail):
        if i == len(trail) - 1:
            lis.append('<li><span aria-current="page"%s>%s</span></li>' % (' id="crumb-current"' if href == "#cur" else "", E(label)))
        else:
            lis.append('<li><a href="%s">%s</a></li>' % (href, E(label)))
    return '<nav class="crumbs wrap" aria-label="Breadcrumb"><ol>%s</ol></nav>' % "".join(lis)

def crumb_ld(trail):
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": l, "item": SITE + h.replace("../", "")} for i, (l, h) in enumerate(trail) if not h.startswith("#")]}

